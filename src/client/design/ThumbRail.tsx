/**
 * 窄档的**底部栏杆**：拇指够得到的那一条。
 *
 * ── 为什么是底部，而不是再往顶上加一行 ────────────────────────────────────
 *
 * 手机端板头的竖向额度是最紧的一处。实测（412×900）：读数 28 + 搜索/巡航/新建 30 +
 * 模式簇 28 + 列导航 28，四行加三份间隙 = 144px；再往顶上加一行，五列就再少 28。
 *
 * 而底部那一条**不占内容的额度**：它浮在滚动区上面，遮住的是列表底部——那里本来
 * 就是要滚过去的区域，不像顶部那样把内容整体往下推。单手操作时，底部也是唯一
 * 「不用换手」的位置。
 *
 * ── 它不是工具栏，是那一页的主行动 ────────────────────────────────────────
 *
 * 这一条只装**一件主行动 + 至多两个常用动作**。装第三个就会长成第二条工具栏，
 * 而那正是它要解决的那个问题（工具多了，顶栏就挤）。
 *
 * ── 它自己不下判断 ────────────────────────────────────────────────────────
 *
 * 谁进来、按下去做什么，全由调用点给（`children`）。这一份只说三件事：它贴在
 * 容器底部、它浮在内容之上、它的内衬与那一条纸面用同一组令牌。页面因此不会
 * 各自发明一条「底栏」。
 */
import css from './components.module.css'

export interface ThumbRailProps {
  /** 栏杆里有什么：通常是一件主行动加一两枚常用动作。 */
  readonly children: React.ReactNode
  /** 无障碍用的名字：这一条是什么（「看板的动作」这类）。 */
  readonly label: string
}

/**
 * 底部栏杆。
 *
 * 它的定位由**父容器**决定（父容器必须是 `position: relative` 的滚动区）：这里是
 * `position: absolute` 而不是 `fixed`——`fixed` 会相对视口、盖到宿主侧栏上，而这个
 * 栏杆只属于这一页的列区。
 * @param props - 里面装什么，叫什么名字。
 * @returns 贴在容器底部的那一条。
 */
export function ThumbRail({ children, label }: ThumbRailProps): React.ReactElement {
  return (
    <div className={css.thumbRail} role="group" aria-label={label} data-dsh-tb-thumbrail="">
      {children}
    </div>
  )
}
