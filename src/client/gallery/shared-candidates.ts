/**
 * 设计系统里**目前只有一个页面在用**的组件，以及它们为什么还没被第二个页面用。
 *
 * ── 这一页为什么要摆这份名单 ────────────────────────────────────────────────
 *
 * `design/` 的准入判据是「有两个消费者」。这条判据管得住**已经**发生的事，管不住
 * 一件更常见的事：一个组件今天只有一页用，明天另一页也要用——而**那一刻没有东西
 * 会提醒任何人该把它搬进来**。
 *
 * 「以后会不会被复用」无法机械判断（那是印象，不是事实）。能机械判断的是「现在被
 * 几处用到」，而这件事本文件不猜：`tests/design-coverage.spec.ts` 每轮都重新数，
 * **本文件的名单与它数出来的不一致就红**。所以这份名单是**派生数据的展示位**，
 * 不是第二份真相——它比代码陈旧的那一刻，门禁就开口。
 *
 * 放在预览页而不是测试输出里，是因为测试跑完就没了：一份只出现在滚动日志里的名单，
 * 下一个人翻不到。
 *
 * ── 名字旁边那句「为什么」什么用 ────────────────────────────────────────────
 *
 * 一条只写名字的清单会被读成「这些是待办」。它其实是三种完全不同的东西，混在一起
 * 就会误导：
 *
 *   1. **表单原件**（`Field` `Input` `Select` `TextArea` `Switch`）：两个面板被有意
 *      给了不同的表单语言，清单那边的字段是专用组合件（日期、标签、整段文字），
 *      不是这几个的薄封装。这是**设计决定**，不是欠账。
 *   2. **只有一边需要的形态**（`Dialog` `Section` `SendModeToggle`）：看板有弹层与
 *      分段控件，清单那一页刻意不用 Dialog（`DESIGN.md` 成文）。
 *   3. **常驻在 `design/` 但当下面板只用了一次**（`ColorSwatches`）：它的第二个
 *      消费者是预览页自己，而预览页不算消费者（否则任何组件都能靠「被摆上预览页」
 *      满足共享判据，那是循环）。
 */
export type SharedCandidate = {
  /** `design/` 导出的组件名。 */
  readonly name: string
  /** 为什么它现在只有一个消费者。写成事实，不写成待办。 */
  readonly why: string
}

/**
 * 名单的真相在 `tests/design-coverage.spec.ts` 的计数里；这里是它的展示面。
 *
 * 加一个组件、或某个组件真的拿到第二个消费者，**这份名单不变就红**——所以它不会
 * 悄悄变旧。
 */
export const SHARED_CANDIDATES: readonly SharedCandidate[] = [
  { name: 'ColorSwatches', why: '预览页是它唯一的第二处；真正的产品消费者只有一处' },
  { name: 'Field', why: '表单原件；两页被有意给了不同的表单语言' },
  { name: 'Input', why: '表单原件；清单的输入是专用组合件，不是它的薄封装' },
  { name: 'Section', why: '设置区块的容器；目前只有看板有那种区块' },
  { name: 'Select', why: '表单原件；清单的选择面是它自己的筛选语法' },
  { name: 'SendModeToggle', why: '排队/插话两态只属于看板的发送器' },
  { name: 'Switch', why: '表单原件；清单的开关是行上的勾选框，语义不同' },
  { name: 'TextArea', why: '表单原件；清单的正文是就地展开的行，不是独立输入框' },
]
